int main(void)
{
    // Radiotap-Länge aus Byte 2 und 3
    uint16_t radiotap_len =
        packet[2] | ((uint16_t)packet[3] << 8);

    printf("Paketlaenge: %zu Bytes\n", sizeof(packet));
    printf("Radiotap-Laenge: %u Bytes\n", radiotap_len);

    // Anfang des 802.11-Frames
    const uint8_t *frame = packet + radiotap_len;

    printf("Frame Control: %02X %02X\n", frame[0], frame[1]);

    // Frame-Control-Informationen
    uint8_t version = frame[0] & 0x03;
    uint8_t type = (frame[0] >> 2) & 0x03;
    uint8_t subtype = (frame[0] >> 4) & 0x0F;

    printf("Version: %u\n", version);
    printf("Type: %u\n", type);
    printf("Subtype: %u\n", subtype);

    // MAC-Adressen
    printf("Destination: ");
    for (int i = 4; i < 10; i++)
        printf("%02X%s", frame[i], i == 9 ? "\n" : ":");

    printf("Source:      ");
    for (int i = 10; i < 16; i++)
        printf("%02X%s", frame[i], i == 15 ? "\n" : ":");

    printf("BSSID:       ");
    for (int i = 16; i < 22; i++)
        printf("%02X%s", frame[i], i == 21 ? "\n" : ":");

    return 0;
}
